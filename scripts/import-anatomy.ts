/**
 * Build-time import: reads yuhonas/free-exercise-db (public domain) and writes, for each seeded exercise,
 * - src/lib/db/exerciseAnatomy.generated.ts: primary muscle, equipment, type, level and the Essentials flag
 * - src/lib/db/exerciseGuide.generated.ts: every instruction step (the detail panel; own lazy chunk)
 *
 * Run: npm run import-anatomy
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GLOBAL_EXERCISES } from '../src/lib/db/seedExercises.generated.ts';
import { CURATED_EXERCISES, CURATED_TWINS, ESSENTIAL_EXTRAS } from '../src/lib/db/seedExercises.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, '../src/lib/db/exerciseAnatomy.generated.ts');
const GUIDE_PATH = join(__dirname, '../src/lib/db/exerciseGuide.generated.ts');

const DATASET_URL =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';

interface SourceExercise {
  id: string;
  name: string;
  primaryMuscles?: string[];
  equipment?: string | null;
  instructions?: string[];
  category?: string | null;
  level?: string | null;
}

const MUSCLES: Record<string, string> = {
  abdominals: 'abs',
  abductors: 'abductors',
  adductors: 'adductors',
  biceps: 'biceps',
  calves: 'calves',
  chest: 'chest',
  forearms: 'forearms',
  glutes: 'glutes',
  hamstrings: 'hamstrings',
  lats: 'lats',
  'lower back': 'lowerBack',
  'middle back': 'midBack',
  neck: 'neck',
  quadriceps: 'quads',
  shoulders: 'shoulders',
  traps: 'traps',
  triceps: 'triceps',
};

const EQUIPMENT: Record<string, string> = {
  barbell: 'barbell',
  'e-z curl bar': 'barbell',
  dumbbell: 'dumbbell',
  kettlebells: 'kettlebell',
  cable: 'cable',
  machine: 'machine',
  'body only': 'bodyweight',
  bands: 'band',
  'medicine ball': 'ball',
  'exercise ball': 'ball',
  'foam roll': 'other',
  other: 'other',
};

const CATEGORIES: Record<string, string> = {
  strength: 'strength',
  powerlifting: 'strength',
  stretching: 'stretching',
  plyometrics: 'plyometrics',
  cardio: 'cardio',
  'olympic weightlifting': 'olympic',
  strongman: 'strongman',
};

const ESSENTIALS = new Set([...CURATED_EXERCISES.map((ex) => ex.name), ...ESSENTIAL_EXTRAS]);

function normalizeName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

async function main(): Promise<void> {
  const res = await fetch(DATASET_URL);
  if (!res.ok) throw new Error(`Failed to fetch dataset: ${res.status}`);
  const source = (await res.json()) as SourceExercise[];
  const byId = new Map(source.map((row) => [row.id, row]));
  const bySlug = new Map(source.map((row) => [row.id.toLowerCase().replace(/_/g, '-'), row]));
  const byName = new Map(source.map((row) => [normalizeName(row.name), row]));

  const lines: string[] = [];
  const guide: string[] = [];
  for (const exercise of GLOBAL_EXERCISES) {
    const twin = CURATED_TWINS[exercise.name];
    const row =
      (twin ? byId.get(twin.id) : undefined) ??
      bySlug.get(exercise.source_slug) ??
      byName.get(normalizeName(exercise.name));
    const essential = ESSENTIALS.has(exercise.name) ? 'e' : '';
    if (!row) {
      if (essential) lines.push(`  ${JSON.stringify(exercise.source_slug)}: ${JSON.stringify(`|||strength|${essential}`)},`);
      continue;
    }
    const steps = (row.instructions ?? []).map((step) => step.trim()).filter(Boolean);
    if (steps.length > 0) guide.push(`  ${JSON.stringify(exercise.source_slug)}: ${JSON.stringify(steps)},`);
    const muscle = MUSCLES[(row.primaryMuscles?.[0] ?? '').toLowerCase()] ?? '';
    const equipment = EQUIPMENT[(twin?.equipment ?? row.equipment ?? '').toLowerCase()] ?? '';
    const category = CATEGORIES[(row.category ?? '').toLowerCase()] ?? '';
    const level = row.level ?? '';
    lines.push(`  ${JSON.stringify(exercise.source_slug)}: ${JSON.stringify(`${muscle}|${equipment}|${level}|${category}|${essential}`)},`);
  }

  const output = `/** Auto-generated by scripts/import-anatomy.ts from free-exercise-db (public domain) — do not edit manually. */
/** source_slug → "muscle|equipment|level|type|e" (any part may be empty; e = Essentials). */
export const EXERCISE_ANATOMY: Record<string, string> = {
${lines.join('\n')}
};
`;
  writeFileSync(OUT_PATH, output, 'utf8');
  writeFileSync(
    GUIDE_PATH,
    `/** Auto-generated by scripts/import-anatomy.ts from free-exercise-db (public domain) — do not edit manually. */
/** source_slug → instruction steps. */
export const EXERCISE_GUIDE: Record<string, string[]> = {
${guide.join('\n')}
};
`,
    'utf8',
  );
  console.log(`Wrote ${lines.length} anatomy rows and ${guide.length} guides`);
}

void main();
