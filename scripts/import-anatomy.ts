/**
 * Build-time import: reads yuhonas/free-exercise-db (public domain) and writes the
 * primary muscle + equipment of each seeded exercise to
 * src/lib/db/exerciseAnatomy.generated.ts, for the offline body-map search.
 *
 * Run: npm run import-anatomy
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GLOBAL_EXERCISES } from '../src/lib/db/seedExercises.generated.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, '../src/lib/db/exerciseAnatomy.generated.ts');

const DATASET_URL =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';

interface SourceExercise {
  id: string;
  name: string;
  primaryMuscles?: string[];
  equipment?: string | null;
}

const MUSCLES: Record<string, string> = {
  abdominals: 'abs',
  abductors: 'abductors',
  adductors: 'adductors',
  biceps: 'biceps',
  calves: 'calves',
  chest: 'chest',
  forearms: 'forearms',
  glutes: 'glutes',
  hamstrings: 'hamstrings',
  lats: 'lats',
  'lower back': 'lowerBack',
  'middle back': 'midBack',
  neck: 'neck',
  quadriceps: 'quads',
  shoulders: 'shoulders',
  traps: 'traps',
  triceps: 'triceps',
};

const EQUIPMENT: Record<string, string> = {
  barbell: 'barbell',
  'e-z curl bar': 'barbell',
  dumbbell: 'dumbbell',
  kettlebells: 'kettlebell',
  cable: 'cable',
  machine: 'machine',
  'body only': 'bodyweight',
  bands: 'band',
  'medicine ball': 'ball',
  'exercise ball': 'ball',
  'foam roll': 'other',
  other: 'other',
};

function normalizeName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

async function main(): Promise<void> {
  const res = await fetch(DATASET_URL);
  if (!res.ok) throw new Error(`Failed to fetch dataset: ${res.status}`);
  const source = (await res.json()) as SourceExercise[];
  const bySlug = new Map(source.map((row) => [row.id.toLowerCase().replace(/_/g, '-'), row]));
  const byName = new Map(source.map((row) => [normalizeName(row.name), row]));

  const lines: string[] = [];
  for (const exercise of GLOBAL_EXERCISES) {
    const row = bySlug.get(exercise.source_slug) ?? byName.get(normalizeName(exercise.name));
    if (!row) continue;
    const muscle = MUSCLES[(row.primaryMuscles?.[0] ?? '').toLowerCase()] ?? '';
    const equipment = EQUIPMENT[(row.equipment ?? '').toLowerCase()] ?? '';
    if (!muscle && !equipment) continue;
    lines.push(`  ${JSON.stringify(exercise.source_slug)}: ${JSON.stringify(`${muscle}|${equipment}`)},`);
  }

  const output = `/** Auto-generated by scripts/import-anatomy.ts from free-exercise-db (public domain) — do not edit manually. */
/** source_slug → "muscle|equipment" (either part may be empty). */
export const EXERCISE_ANATOMY: Record<string, string> = {
${lines.join('\n')}
};
`;
  writeFileSync(OUT_PATH, output, 'utf8');
  console.log(`Wrote ${lines.length} anatomy rows to ${OUT_PATH}`);
}

void main();
